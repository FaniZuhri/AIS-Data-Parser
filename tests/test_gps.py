class TestGsa:
    def test_published_example_skips_empty_prn_slots(self) -> None:
        message = decode("$GPGSA,A,3,04,05,,09,12,,,24,,,,,2.5,1.3,2.1*39")
        assert isinstance(message, Gsa)
        assert message.selection_mode == "A"
        assert message.fix_type == 3
        assert message.fix_type_text == "3D fix"
        assert message.active_prns == (4, 5, 9, 12, 24)
        assert message.pdop == pytest.approx(2.5)
        assert message.hdop == pytest.approx(1.3)
        assert message.vdop == pytest.approx(2.1)
        assert message.system_id is None

    def test_no_fix(self) -> None:
        message = decode(nmea("GPGSA,A,1,,,,,,,,,,,,,,,"))
        assert isinstance(message, Gsa)
        assert message.fix_type_text == "no fix"
        assert message.active_prns == ()

    def test_nmea_411_system_id(self) -> None:
        message = decode(nmea("GNGSA,A,3,04,05,,09,12,,,24,,,,,2.5,1.3,2.1,1"))
        assert isinstance(message, Gsa)
        assert message.system_id == "1"


class TestGsv:
    def test_published_example(self) -> None:
        message = decode("$GPGSV,3,1,11,03,03,111,00,04,15,270,00,06,01,010,00,13,06,292,00*74")
        assert isinstance(message, Gsv)
        assert message.messages_total == 3
        assert message.message_number == 1
        assert message.satellites_in_view == 11
        assert len(message.satellites) == 4
        assert message.satellites[0].prn == 3
        assert message.satellites[0].elevation_deg == pytest.approx(3)
        assert message.satellites[0].azimuth_deg == pytest.approx(111)
        assert message.satellites[0].snr_db == pytest.approx(0)
        assert message.satellites[3].prn == 13
        assert message.signal_id is None

    def test_trailing_signal_id_is_not_mistaken_for_a_satellite(self) -> None:
        message = decode(nmea("GPGSV,1,1,04,03,03,111,00,04,15,270,00,06,01,010,00,13,06,292,00,7"))
        assert isinstance(message, Gsv)
        assert message.signal_id == 7
        assert len(message.satellites) == 4
        assert [sat.prn for sat in message.satellites] == [3, 4, 6, 13]

    def test_untracked_satellite_has_null_snr(self) -> None:
        message = decode(nmea("GPGSV,1,1,01,03,03,111,"))
        assert isinstance(message, Gsv)
        assert message.satellites[0].snr_db is None

    def test_partial_trailing_quadruple_is_ignored(self) -> None:
        message = decode(nmea("GPGSV,1,1,02,03,03,111,00,04,15"))
        assert isinstance(message, Gsv)
        assert len(message.satellites) == 1


