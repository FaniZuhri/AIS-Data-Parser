class TestCoordinateValidation:
    @pytest.mark.parametrize(
        ("lat", "hemisphere"),
        [
            ("4807.038", ""),  # missing indicator: must not default to North
            ("4807.038", "X"),
            ("", "N"),  # missing value
            ("not-a-number", "N"),
            ("4860.000", "N"),  # minutes >= 60 is malformed
            ("9900.000", "N"),  # degrees beyond the pole
            ("-4807.038", "N"),  # explicit signs are not permitted
        ],
    )
    def test_unusable_latitude_is_none(self, lat: str, hemisphere: str) -> None:
        message = decode(nmea(f"GPGGA,123519,{lat},{hemisphere},01131.000,E,1,08,0.9,545.4,M,46.9,M,,"))
        assert isinstance(message, Gga)
        assert message.latitude_deg is None

    def test_southern_and_western_are_negative(self) -> None:
        message = decode(nmea("GPGGA,123519,4807.038,S,01131.000,W,1,08,0.9,545.4,M,46.9,M,,"))
        assert isinstance(message, Gga)
        assert message.latitude_deg == pytest.approx(-48.1173)
        assert message.longitude_deg == pytest.approx(-11.5166667)

    def test_three_digit_longitude_degrees(self) -> None:
        message = decode(nmea("GPGGA,123519,0119.000,N,10651.2345,E,1,08,0.9,545.4,M,46.9,M,,"))
        assert isinstance(message, Gga)
        assert message.longitude_deg == pytest.approx(106.8539083)

    def test_longitude_beyond_180_is_rejected(self) -> None:
        message = decode(nmea("GPGGA,123519,4807.038,N,19031.000,E,1,08,0.9,545.4,M,46.9,M,,"))
        assert isinstance(message, Gga)
        assert message.longitude_deg is None


