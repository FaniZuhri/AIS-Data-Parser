class TestFixOf:
    def test_extracts_from_gga_rmc_and_gll(self) -> None:
        for sentence in (
            "$GPGGA,123519,4807.038,N,01131.000,E,1,08,0.9,545.4,M,46.9,M,,*47",
            "$GPRMC,123519,A,4807.038,N,01131.000,E,022.4,084.4,230394,003.1,W*6A",
        ):
            message = decode_sentence(parse_sentence(sentence))
            assert message is not None
            fix = fix_of(message)
            assert fix is not None
            assert fix.latitude_deg == pytest.approx(48.1173)
            assert fix.longitude_deg == pytest.approx(11.5166667)

    def test_returns_none_without_a_position(self) -> None:
        message = decode_sentence(parse_sentence(nmea("GPGSV,1,1,00")))
        assert message is not None
        assert fix_of(message) is None

    def test_returns_none_for_a_void_fix(self) -> None:
        message = decode_sentence(parse_sentence(nmea("GPGGA,000000,0000.000,N,00000.000,E,0,00,,,M,,M,,")))
        assert message is not None
        assert fix_of(message) is None
