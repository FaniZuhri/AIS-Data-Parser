"""Tests for the NMEA 0183 GPS/GNSS sentence decoders.

Published example sentences carry their real checksums, so these tests exercise
the decoders against authoritative reference data rather than against
sentences generated by the code under test.
"""

from __future__ import annotations

import pytest

from aivdm.gps import (
    Gga,
    Gll,
    Gsa,
    Gsv,
    Hdg,
    Hdt,
    Rmc,
    Rot,
    Vtg,
    Zda,
    decode_sentence,
    fix_of,
)
from aivdm.nmea import parse_sentence


def nmea(body: str) -> str:
    """Build a sentence with an independently computed checksum."""
    value = 0
    for char in body:
        value ^= ord(char)
    return f"${body}*{value:02X}"


def decode(sentence: str) -> object:
    return decode_sentence(parse_sentence(sentence))


class TestGga:
    def test_published_example(self) -> None:
        parsed = parse_sentence("$GPGGA,123519,4807.038,N,01131.000,E,1,08,0.9,545.4,M,46.9,M,,*47")
        message = decode_sentence(parsed)
        assert isinstance(message, Gga)
        assert message.utc_time == "123519"
        assert message.latitude_deg == pytest.approx(48.1173)
        assert message.longitude_deg == pytest.approx(11.5166667)
        assert message.fix_quality == 1
        assert message.fix_quality_text == "GPS fix"
        assert message.satellites_used == 8
        assert message.hdop == pytest.approx(0.9)
        assert message.altitude_m == pytest.approx(545.4)
        assert message.geoid_separation_m == pytest.approx(46.9)
        assert message.dgps_age_s is None
        assert message.dgps_station_id is None

    def test_fix_quality_zero_suppresses_a_zero_filled_position(self) -> None:
        # The classic trap: receivers zero-fill an invalid fix, which would
        # otherwise decode as a real position in the Gulf of Guinea.
        message = decode(nmea("GPGGA,000000,0000.000,N,00000.000,E,0,00,,,M,,M,,"))
        assert isinstance(message, Gga)
        assert message.fix_quality == 0
        assert message.fix_quality_text == "fix not available"
        assert message.latitude_deg is None
        assert message.longitude_deg is None

    def test_empty_fields_are_none_not_zero(self) -> None:
        message = decode(nmea("GPGGA,,,,,,0,00,,,,,,"))
        assert isinstance(message, Gga)
        assert message.utc_time is None
        assert message.latitude_deg is None
        assert message.longitude_deg is None
        assert message.altitude_m is None
        assert message.hdop is None

    def test_dgps_fields(self) -> None:
        message = decode(nmea("GPGGA,123519,4807.038,N,01131.000,E,2,07,0.8,100.0,M,45.0,M,2.5,0123"))
        assert isinstance(message, Gga)
        assert message.fix_quality_text == "differential GPS fix"
        assert message.dgps_age_s == pytest.approx(2.5)
        assert message.dgps_station_id == "0123"

    def test_truncated_sentence_does_not_raise(self) -> None:
        message = decode("$GPGGA,123519")
        assert isinstance(message, Gga)
        assert message.latitude_deg is None

    def test_gnss_talker_decodes_identically(self) -> None:
        message = decode(nmea("GNGGA,123519,4807.038,N,01131.000,E,1,08,0.9,545.4,M,46.9,M,,"))
        assert isinstance(message, Gga)
        assert message.latitude_deg == pytest.approx(48.1173)


class TestRmc:
    def test_published_example(self) -> None:
        message = decode("$GPRMC,123519,A,4807.038,N,01131.000,E,022.4,084.4,230394,003.1,W*6A")
        assert isinstance(message, Rmc)
        assert message.utc_time == "123519"
        assert message.utc_date == "230394"
        assert message.status == "A"
        assert message.latitude_deg == pytest.approx(48.1173)
        assert message.longitude_deg == pytest.approx(11.5166667)
        assert message.sog_knots == pytest.approx(22.4)
        assert message.cog_deg == pytest.approx(84.4)
        assert message.magnetic_variation_deg == pytest.approx(-3.1)

    def test_west_variation_is_negative_and_east_positive(self) -> None:
        west = decode(nmea("GPRMC,123519,A,4807.038,N,01131.000,E,022.4,084.4,230394,003.1,W"))
        east = decode(nmea("GPRMC,123519,A,4807.038,N,01131.000,E,022.4,084.4,230394,003.1,E"))
        assert isinstance(west, Rmc) and isinstance(east, Rmc)
        assert west.magnetic_variation_deg == pytest.approx(-3.1)
        assert east.magnetic_variation_deg == pytest.approx(3.1)

    def test_missing_variation_indicator_is_none_not_negative(self) -> None:
        message = decode(nmea("GPRMC,123519,A,4807.038,N,01131.000,E,022.4,084.4,230394,003.1,"))
        assert isinstance(message, Rmc)
        assert message.magnetic_variation_deg is None

    def test_status_void_suppresses_position(self) -> None:
        message = decode(nmea("GPRMC,123519,V,4807.038,N,01131.000,E,022.4,084.4,230394,003.1,W"))
        assert isinstance(message, Rmc)
        assert message.status == "V"
        assert message.latitude_deg is None
        assert message.longitude_deg is None

    def test_nmea_23_mode_field(self) -> None:
        message = decode(nmea("GPRMC,123519,A,4807.038,N,01131.000,E,022.4,084.4,230394,003.1,W,A"))
        assert isinstance(message, Rmc)
        assert message.mode == "A"


