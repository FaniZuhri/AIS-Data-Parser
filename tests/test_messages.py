    @pytest.mark.parametrize(
        ("raw", "expected"),
        [
            (60, "not available"),
            (61, "manual input mode"),
            (62, "estimated (dead reckoning) mode"),
            (63, "positioning system inoperative"),
        ],
    )
    def test_second_special_values(self, raw: int, expected: str) -> None:
        payload, fill_bits = build(position_report_fields(second=raw))
        message = decode_payload(payload, fill_bits)
        assert isinstance(message, PositionReport)
        assert message.utc_second is None
        assert message.utc_second_status == expected

    def test_sog_at_max_reports_the_floor(self) -> None:
        payload, fill_bits = build(position_report_fields(sog=1022))
        message = decode_payload(payload, fill_bits)
        assert isinstance(message, PositionReport)
        # 1022 means "102.2 knots or more"; sog_raw is the escape hatch.
        assert message.sog_raw == 1022
        assert message.sog_knots == 102.2

    @pytest.mark.parametrize("raw", [1, 20, 126])
    def test_rot_formula_matches_the_spec(self, raw: int) -> None:
        payload, fill_bits = build(position_report_fields(rot=raw))
        message = decode_payload(payload, fill_bits)
        assert isinstance(message, PositionReport)
        # ROT_AIS = 4.733 * sqrt(ROT_sensor), so decode by dividing and squaring.
        assert message.rot_deg_per_min == pytest.approx(round((raw / 4.733) ** 2, 6))
        assert message.rot_saturation_deg_per_min is None
        assert message.rot_text is None

    def test_negative_rot_is_port(self) -> None:
        payload, fill_bits = build(position_report_fields(rot=-20))
        message = decode_payload(payload, fill_bits)
        assert isinstance(message, PositionReport)
        assert message.rot_raw == -20
        assert message.rot_deg_per_min == pytest.approx(-round((20 / 4.733) ** 2, 6))
        assert message.rot_text is None

    def test_raw_one_is_not_confused_with_not_turning(self) -> None:
        # (1/4.733)**2 == 0.044640288. Rounding to one decimal would collapse
        # this to 0.0, which reads as "not turning" — a different statement.
        payload, fill_bits = build(position_report_fields(rot=1))
        message = decode_payload(payload, fill_bits)
        assert isinstance(message, PositionReport)
        assert message.rot_deg_per_min == pytest.approx(0.04464, abs=1e-9)
        assert message.rot_deg_per_min != 0.0

    @pytest.mark.parametrize("raw", [127, -127])
    def test_turning_sentinels_carry_no_magnitude_but_expose_the_saturation(
        self, raw: int
    ) -> None:
        """Pins the deliberate divergence from decoders that skip the sentinel check.

        aggsoft (and any decoder that applies the formula blindly) reports
        ``(127 / 4.733) ** 2 == 720.003210529537`` for raw 127. That is where the
        *encoding* saturates, not a measured rate: the spec defines 127 as
        "turning, no turn indicator available", and 1..126 already covers up to
        708.709. The magnitude therefore stays null and the bound is reported
        separately.
        """
        payload, fill_bits = build(position_report_fields(rot=raw))
        message = decode_payload(payload, fill_bits)
        assert isinstance(message, PositionReport)
        assert message.rot_raw == raw
        assert message.rot_deg_per_min is None
        assert message.rot_saturation_deg_per_min == pytest.approx(720.003211)
        assert message.rot_text is not None
        assert message.rot_text.startswith("turning right" if raw > 0 else "turning left")

    def test_the_encoding_really_does_saturate_at_127(self) -> None:
        # Guards the arithmetic behind rot_saturation_deg_per_min.
        payload, fill_bits = build(position_report_fields(rot=126))
        message = decode_payload(payload, fill_bits)
        assert isinstance(message, PositionReport)
        assert message.rot_deg_per_min == pytest.approx(708.709218)
        assert message.rot_saturation_deg_per_min is None


