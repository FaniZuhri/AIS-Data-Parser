    def test_truncated_420_bit_variant_still_yields_the_identity(self) -> None:
        # Type 5 turns up at 420/422/426 bits in the wild. At 420 the destination
        # tail is lost, but every identity field -- which is what the requester
        # actually asked for -- survives intact.
        full, _ = build(
            [
                (5, 6),
                (0, 2),
                (367533950, 30),
                (0, 2),  # AIS version
                (9134270, 30),  # IMO number
                *six("3FOF8", 7),
                *six("EVER DIADEM", 20),
                (70, 8),  # ship type
                (225, 9),  # dim to bow
                (70, 9),  # dim to stern
                (1, 6),
                (31, 6),
                (1, 4),  # EPFD
                (5, 4),  # ETA month
                (15, 5),  # ETA day
                (14, 5),  # ETA hour
                (30, 6),  # ETA minute
                (123, 8),  # draught, tenths of a metre
                *six("NEW YORK", 20),
                (0, 1),  # DTE
                (0, 1),  # spare
            ]
        )
        assert len(full) == 71  # 426 armored bits, 2 of them fill -> 424

        message = decode_payload(full[:70], 0)  # exactly 420 bits
        assert isinstance(message, StaticVoyageData)
        assert message.name == "EVER DIADEM"
        assert message.call_sign == "3FOF8"
        assert message.imo_number == 9134270
        assert message.ship_type == 70
        assert message.dimensions.bow == 225
        assert message.draught_m == pytest.approx(12.3)
        assert message.eta.month == 5
        # Only the tail is lost.
        assert message.destination == ""
        assert message.dte is None

