def decode(*sentences: str):
    """Run sentences through framing, reassembly and decoding."""
    assembler = FragmentAssembler()
    for sentence in sentences:
        assembled = assembler.push(parse_aivdm(parse_sentence(sentence)))
        if assembled is not None:
            return decode_payload(assembled.payload, assembled.fill_bits)
    raise AssertionError("no payload was assembled")


