class TestDegenerateInput:
    def test_unknown_message_type_is_preserved(self) -> None:
        payload, fill_bits = build([(28, 6), (0, 2), (123456789, 30), (0, 8)])
        message = decode_payload(payload, fill_bits)
        assert isinstance(message, UnknownMessage)
        assert message.message_type == 28
        assert message.mmsi == 123456789
        assert message.payload == payload

    def test_truncated_payload_degrades_to_unknown_not_an_exception(self) -> None:
        payload, fill_bits = build([(5, 6), (0, 2), (1, 30)])
        message = decode_payload(payload, fill_bits)
        assert isinstance(message, UnknownMessage)
        assert message.message_type == 5

    def test_five_bit_payload_yields_an_unknown_with_no_mmsi(self) -> None:
        payload, fill_bits = build([(1, 6)], total_bits=5)
        message = decode_payload(payload, fill_bits)
        assert isinstance(message, UnknownMessage)
        assert message.mmsi is None

    def test_bit_length_reflects_fill_bits(self) -> None:
        unknown = decode_payload("0", 0)
        assert isinstance(unknown, UnknownMessage)
        assert unknown.bit_length == 6

        trimmed = decode_payload("0", 2)
        assert isinstance(trimmed, UnknownMessage)
        assert trimmed.bit_length == 4

    def test_payload_shorter_than_the_type_field_is_reported_as_type_zero(self) -> None:
        payload, fill_bits = build([(1, 6)], total_bits=5)
        message = decode_payload(payload, fill_bits)
        assert isinstance(message, UnknownMessage)
        # 0 is not a valid AIS message type, so it cannot be mistaken for one.
        assert message.message_type == 0
        assert message.repeat is None
        assert message.mmsi is None
